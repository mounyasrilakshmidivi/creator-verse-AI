// Builds supabase/SETUP_ALL_IN_ONE.sql: every file in supabase/migrations, in order, inside ONE transaction,
// so the whole database can be set up with a single paste into the Supabase SQL Editor (all-or-nothing).
// Run: npm run setup-sql
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const dir = 'supabase/migrations';
const files = readdirSync(dir).filter(f => f.endsWith('.sql')).sort();
const parts = files.map(f => `-- ======================================================================\n-- ${f}\n-- ======================================================================\n${readFileSync(`${dir}/${f}`, 'utf8').trim()}\n`);
const out = `-- CreatorVerse AI: complete database setup (generated by scripts/combine-migrations.mjs; do not edit by hand)
-- HOW TO USE: Supabase dashboard -> SQL Editor -> New query -> paste this whole file -> Run.
-- Runs as one transaction: if anything fails, nothing is changed and you can fix the problem and run it again.
-- It creates tables, security policies and functions only. It does not delete or change any existing data.
-- Run it ONCE on a new project. (If it reports that a table "already exists", the setup was already applied.)

begin;

${parts.join('\n')}
commit;
`;
writeFileSync('supabase/SETUP_ALL_IN_ONE.sql', out);
console.log(`supabase/SETUP_ALL_IN_ONE.sql written from ${files.length} migrations (${(out.length / 1024).toFixed(0)} KB)`);
